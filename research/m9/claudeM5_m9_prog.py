#!/usr/bin/env python3
"""claudeM5_m9_prog.py: pull M9. Progressions of 3-gaps in the gate. M82's cores reduce both of M81's laws to one: after
two samples inside the gate trap, the gate never has five 3-gaps whose starts are d = 23 samples apart, whatever fills
the stretches between them. Which steps d allow k such 3-gaps, late?

The instance is M80's (claudeM5_m9_sat.py, imported unchanged for the trap, the simulator and the DIMACS writer; the
rule and trap clauses are generated by the same loops, and a control checks that they are identical to M80's). Only
the samples of the progression are fixed: column 1 black at s and s + 3 for s = P + i d, i = 0..k-1. Inside the trap
every gap is 3 or 5, so two blacks 3 samples apart are a 3-gap. Every other sample is free.

  python3 claudeM5_m9_prog.py KITFILE OUTDIR control
  python3 claudeM5_m9_prog.py KITFILE OUTDIR one D K P          one instance
SAT: the model's initial row is simulated cell by cell (start and every sample window in the trap; the progression's
samples black). UNSAT: CaDiCaL's LRAT checked by cake_lpr. No time limit (the owner, 21 November).
"""
import hashlib
import importlib.util
import json
import pathlib
import subprocess
import sys
import time

HERE = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('m9sat', HERE / 'claudeM5_m9_sat.py')
S = importlib.util.module_from_spec(spec)
spec.loader.exec_module(S)


def build_units(trap, last, units):
    """M80's clauses for samples 0..last, with column 1 fixed only at the samples in `units` (sample -> 0/1)."""
    T = 2 * last
    M = T + 1
    vid = {}

    def v(tau, j):
        k = (tau, j)
        if k not in vid:
            vid[k] = len(vid) + 1
        return vid[k]

    cl = []
    for tau in range(T):
        for j in range(1, M - tau):
            z, b, c = v(tau + 1, j), v(tau, j), v(tau, j + 1)
            if j == 1:
                a0 = 1 if tau % 2 == 1 else 0
                for bb in (0, 1):
                    for cc in (0, 1):
                        zz = a0 ^ (bb | cc)
                        cl.append([(-b if bb else b), (-c if cc else c), (z if zz else -z)])
            else:
                a = v(tau, j - 1)
                for aa in (0, 1):
                    for bb in (0, 1):
                        for cc in (0, 1):
                            zz = aa ^ (bb | cc)
                            cl.append([(-a if aa else a), (-b if bb else b), (-c if cc else c), (z if zz else -z)])
    for s in sorted(units):
        cl.append([v(2 * s, 1) if units[s] else -v(2 * s, 1)])
    ncell = len(vid)
    sel = [ncell + 1 + i for i in range(len(trap))]
    cl.append(sel)
    for i, code in enumerate(trap):
        for j in range(16):
            cl.append([-sel[i], v(0, j + 1) if (code >> j) & 1 else -v(0, j + 1)])
    return cl, vid, ncell + len(trap), T, M


def progression(d, k, P):
    units = {}
    for i in range(k):
        units[P + i * d] = 1
        units[P + i * d + 3] = 1
    return units, P + (k - 1) * d + 3


def verify(model, vid, trap, T, M, units):
    pos = set(x for x in model if x > 0)
    row = [1 if vid[(0, j)] in pos else 0 for j in range(1, M + 1)]
    rows = S.simulate(row, T)
    ts = set(trap)
    win = lambda r: sum(r[j + 1] << j for j in range(16))
    samples = [rows[2 * s][1] for s in range(T // 2 + 1)]
    ok = (win(rows[0]) in ts and all(win(rows[2 * s]) in ts for s in range(T // 2 + 1))
          and all(samples[s] == u for s, u in units.items())
          and all((vid[(tau, j)] in pos) == bool(rows[tau][j]) for (tau, j) in vid))
    gaps = []
    blacks = [s for s, x in enumerate(samples) if x]
    for a, b in zip(blacks, blacks[1:]):
        gaps.append(b - a)
    return ok, win(rows[0]), ''.join(map(str, gaps))


def solve(trap, outdir, d, k, P, label=None):
    out = pathlib.Path(outdir)
    out.mkdir(parents=True, exist_ok=True)
    units, last = progression(d, k, P)
    tag = label or 'd%d_k%d_P%d' % (d, k, P)
    cl, vid, nv, T, M = build_units(trap, last, units)
    cnf = out / (tag + '.cnf')
    S.dimacs(cl, nv, cnf)
    res = dict(d=d, k=k, P=P, last_sample=last, variables=nv, clauses=len(cl),
               cnf_sha=hashlib.sha256(cnf.read_bytes()).hexdigest())
    t0 = time.time()
    p = subprocess.run(['kissat', '-q', str(cnf)], capture_output=True, text=True)
    res['solve_seconds'] = round(time.time() - t0, 1)
    res['status'] = {10: 'SAT', 20: 'UNSAT'}.get(p.returncode, 'UNKNOWN')
    if res['status'] == 'SAT':
        model = [int(x) for line in p.stdout.splitlines() if line.startswith('v ') for x in line[2:].split()]
        res['verified'], res['start_window'], res['gaps'] = verify(model, vid, trap, T, M, units)
    elif res['status'] == 'UNSAT':
        proof = out / (tag + '.lrat')
        q = subprocess.run(['cadical', '-q', '--lrat=true', str(cnf), str(proof)], capture_output=True, text=True)
        r = subprocess.run(['cake_lpr', str(cnf), str(proof)], capture_output=True, text=True)
        res['certificate'] = q.returncode == 20 and 's VERIFIED UNSAT' in r.stdout
        res['proof_bytes'] = proof.stat().st_size
        proof.unlink()
    cnf.unlink()
    (out / (tag + '.json')).write_text(json.dumps(res))
    line = 'd = %2d, k = %d, P = %2d: %-7s %6d variables, solve %7.1f s' % (d, k, P, res['status'], nv,
                                                                             res['solve_seconds'])
    if res['status'] == 'SAT':
        line += '; verified %s; gaps after sample %d: %s' % (res['verified'], P, res['gaps'][:60])
    if 'certificate' in res:
        line += '; LRAT checked by cake_lpr: %s' % res['certificate']
    print(line, flush=True)
    return res


def control(trap, outdir):
    """The builder reproduces M80's CNF exactly for the four-run word at P = 2 (every head and white fixed), and the
    reduced progression at d = 23 equals M82's core samples in meaning: blacks 3 apart, 23 apart, five times."""
    word, P = '3' + '55553' * 4, 2
    cl80, vid80, nv80, info = S.build(trap, word, P)
    wh = info['heads']
    units = {P + s: h for s, h in enumerate(wh)}
    cl, vid, nv, T, M = build_units(trap, P + len(wh) - 1, units)
    same = cl == cl80 and vid == vid80 and nv == nv80
    print('the builder reproduces M80\'s CNF for 3(55553)^4 at P = 2, clause for clause: %s' % same)
    return same


if __name__ == '__main__':
    a = sys.argv[1:]
    trap = S.trap_codes(a[0])
    if a[2] == 'control':
        sys.exit(0 if control(trap, a[1]) else 1)
    solve(trap, a[1], int(a[3]), int(a[4]), int(a[5]))
