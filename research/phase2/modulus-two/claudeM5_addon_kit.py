"""K92.4, claudeM5 (M236): the modulus-two add-on as three kit modules, cut from this folder's research modules.

The add-on builds on the kit's Rule30FallResidues (from the S32 entry) and does not repeat it. Its proofs are the
research modules' (lean/FastRank, LagCert, TwoCover, TwoCerts, TwoFalls), unchanged except for these edits:
  * namespace PhaseFalls.Moduli becomes Ruliology.CellularAutomata.Rule30FallParities, which opens
    Rule30FallResidues, whose strip, slice, coverage, Fall and Cofinal are the same as S32's research modules';
  * from FastRank only the utilities are kept (loops, fields, the raw step, the raw coverage test and
    phase_extendF); its packed checker for S32's own tables is not needed;
  * the kit's module header, `public import` lines and `@[expose] public section`, and module docstrings.
Output:
  Rule30Certificates/FallParityLag.lean   the any-lag certificates, their three checkers, coverage for GoodAny
  Rule30Certificates/FallParityData.lean  the fifteen certificates and the classification to width 27 (goodAny27)
  Rule30FallParities.lean                 rows of any width, the step to the seed, two_parities_every_27
Usage: python3 claudeM5_addon_kit.py LEAN_DIR OUT_DIR   (OUT_DIR mirrors lean/Ruliology/CellularAutomata)
"""
import pathlib, sys

NS = 'Ruliology.CellularAutomata.Rule30FallParities'

def body(path, after, before=None, start=None):
    """The text of `path` after the line `after` (and from `start`, if given) up to `before` or the namespace end."""
    s = path.read_text(encoding='utf-8')
    i = s.index(after) + len(after)
    if start is not None: i = s.index(start, i)
    j = s.index(before, i) if before else s.index('end PhaseFalls.Moduli', i)
    return s[i:j].strip('\n')

def module(imports, doc, opens, parts, options=()):
    out = ['module', '']
    out += [f'public import {m}' for m in imports]
    out += ['', doc.strip('\n'), '', '@[expose] public section', '', f'namespace {NS}', '', opens, '']
    out += list(options)
    if options: out.append('')
    out.append('\n\n'.join(p for p in parts if p))
    out += ['', f'end {NS}', '']
    return '\n'.join(out)

LAG_DOC = '''/-!
# Adjacent pairs that repeat with any lag, on the strip with one permitted fall residue per site

Support for `Rule30FallParities`. Jen's theorem forbids two eventually periodic singleton columns with any periods, so
the strip argument of `Rule30FallResidues` needs only `GoodAny`: every path of the strip graph has an adjacent pair
that eventually repeats with some lag.

* `pairAny_of_records`: a rank that no edge raises, and along edges of equal rank a class whose position advances by
  one modulo its period, with the class's pair reading the class's word, give `PairAny` on every path.
* `checkLag`, `checkEv`, `checkProd`: the records as a table over every node; a table that only marks where paths
  eventually stay (`EvIn`); and a table over the product of two such sets, for a strip cut in two.
* `classify_stepAny`, `of_emptyAny`: the coverage by substrips of `Rule30FallResidues`, for `GoodAny`.
* The checks use only raw `Nat` operations and loops on `Nat.rec`'s predecessor, so that the kernel evaluates them
  quickly; each is proved sound.
-/'''

DATA_DOC = '''/-!
# Every parity assignment of a 27-cell strip forces a repeating adjacent pair

Support for `Rule30FallParities`. Fifteen certificates, of widths 4 to 20: nine as full tables (`checkLag`), and six
as tables over the product of where the two halves of the strip eventually stay (`checkEv`, `checkProd`). The
assignments still possible at each width, from 3 to 27, are those whose two narrower restrictions are; none is left
at 27 (`goodAny27`). The lists and the certificates were generated by computer search and are checked by the kernel.
-/'''

MAIN_DOC = '''/-!
# Rule 30: falls on both parities in every 27 adjacent singleton columns

A column *falls* at tick `t` when it is black at `t` and white at `t + 1` (`Rule30FallResidues.Fall`).

* `two_parities_every_27`: for every integer `i`, one of the 27 columns `i, …, i + 26` of Rule 30 from a single
  black cell has falls on even ticks and on odd ticks, each after every cutoff (`Rule30FallResidues.Cofinal`).
* `two_cofinal_from_goodAny`: the step to the single seed, for any width and modulus. If every column of a strip
  kept its late falls to one residue, the strip would follow a path of the strip graph, and `GoodAny` would make two
  of its columns eventually periodic, which Jen's theorem forbids.

With `Rule30FallResidues.two_cofinal_every_modulus` (six columns for every modulus from three), every modulus from
two has two cofinal falling residues in every 27 adjacent columns. At modulus two the six-cell strip is not enough
(`Rule30FallResidues.not_good_parity`).
-/'''

def main():
    src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    fr, lc, tc, tcerts, tf = (src / f'{n}.lean' for n in ['FastRank', 'LagCert', 'TwoCover', 'TwoCerts', 'TwoFalls'])
    open1 = 'open Ruliology.CellularAutomata Rule30StripCertificates\n'
    util = body(fr, open1, '/-- A packed certificate:')
    phase = body(fr, open1, '/-- `classify_step` with packed certificates. -/', start='theorem phase_extendF')
    rawcov = body(fr, open1, start='/-! ### Coverage with raw comparisons -/')
    lag = body(lc, open1)
    open2 = 'open Ruliology.CellularAutomata Rule30StripCertificates Rule30Jen\n'
    cover = body(tc, open2, '/-! ### Physical rows of any width -/')
    rows = body(tc, open2, start='/-! ### Physical rows of any width -/')
    opt = 'set_option maxHeartbeats 0\n'
    certs = body(tcerts, opt)
    chain = body(tf, opt, '/-- **Modulus two.**')
    head = body(tf, opt, start='/-- **Modulus two.**')
    opens = 'open Ruliology.CellularAutomata Rule30StripCertificates Rule30FallResidues'
    cert_dir = out / 'Rule30Certificates'
    cert_dir.mkdir(parents=True, exist_ok=True)
    files = {
        cert_dir / 'FallParityLag.lean': module(
            ['Ruliology.CellularAutomata.Rule30Certificates.FallResidueStrip'], LAG_DOC, opens,
            [util, phase, rawcov, lag, cover]),
        cert_dir / 'FallParityData.lean': module(
            ['Ruliology.CellularAutomata.Rule30Certificates.FallParityLag'], DATA_DOC, opens, [certs, chain],
            ['set_option maxRecDepth 100000', 'set_option maxHeartbeats 0']),
        out / 'Rule30FallParities.lean': module(
            ['Ruliology.CellularAutomata.Rule30FallResidues',
             'Ruliology.CellularAutomata.Rule30Certificates.FallParityData'], MAIN_DOC, opens + ' Rule30Jen',
            [rows, head]),
    }
    for p, t in files.items():
        assert 'PhaseFalls' not in t and 'claude' not in t.lower() and 'gpt' not in t.lower(), p
        p.write_text(t, encoding='utf-8')
        print(p, len(t.encode('utf-8')), 'bytes')

if __name__ == '__main__':
    main()
