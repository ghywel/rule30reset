"""K92.4, claudeM5 (M234): repack one of S32's data modules (ModulusData<m>.lean) for FastRank.checkFast.

The certificates are unchanged: each one's per-phase rank numbers are joined into one number (6 bits per node,
node p * 2^w + s), and its rank words into another (3 + 2m bits per rank). The checks become checkFast and the
coverage proofs go through ruledOutFast_eq. Usage: python3 claudeM5_repack.py ModulusData<m>.lean FastData<m>.lean m
"""
import re, sys
src, dst, m = sys.argv[1], sys.argv[2], int(sys.argv[3])
s = open(src).read()
F = 3 + 2*m
cert_re = re.compile(r'⟨\[([0-9, ]*)\], #\[([0-9a-fx, ]*)\], #\[([0-9a-fx, ]*)\]⟩')
def conv_group(body, w):
    N = 2**w
    out = []
    for lab, rk, rd in cert_re.findall(body):
        ranks = [int(x, 0) for x in rk.split(',')]
        reads = [int(x, 0) for x in rd.split(',')]
        assert len(ranks) == m, (len(ranks), m)
        assert all(r < 2**(6*N) for r in ranks)
        assert all(g < 2**F for g in reads)
        R = sum(r << (6*N*p) for p, r in enumerate(ranks))
        G = sum(g << (F*i) for i, g in enumerate(reads))
        out.append(f'  ⟨[{lab}], {hex(R)}, {hex(G)}⟩')
    return out
lines = []
pos = 0
out = s.replace('import ModulusLayers', 'import FastRank').replace('/-! Generated by build_modulus_tables.py. The kernel', '/-! Generated by build_modulus_tables.py and repacked for `checkFast`. The kernel')
def group_sub(mo):
    name, w, body = mo.group(1), int(mo.group(2)), mo.group(3)
    certs = conv_group(body, w)
    return f'private def {name} : List FastCert := [\n' + ',\n'.join(certs) + ',\n]'
out = re.sub(r'private def (group(\d+)_\d+) : List Certificate := \[(.*?)\n\]', group_sub, out, flags=re.S)
out = out.replace('(check ', '(checkFast ')
out = out.replace('Certificate.labels', 'FastCert.labels')
out = out.replace('([] : List Certificate)', '([] : List FastCert)')
out = out.replace('classify_step ', 'classify_stepFast ')
import re as _re
out = _re.sub(r'(private theorem cover\d+ : ruledOut (\d+) (\(?[^=]*\)?) (rest\d+) = (certs\d+)\.map FastCert\.labels) := by decide \+kernel', lambda mo: mo.group(1)+' := by rw [← ruledOutFast_eq]; decide +kernel', out)
assert 'Certificate :=' not in out
open(dst, 'w').write(out)
print('ok', dst, len(out))
