"""Write the finite certificate as 243 tables, normalized by the western fall phase."""
from pathlib import Path

from rank_six import build, matching_tags, pack_row, verify
from probe import transitions


def digits(a):
    return tuple((a // 3**i) % 3 for i in range(6))


def main():
    steps = list(transitions(6))
    options = matching_tags()
    masks = []
    for a in range(243):
        phases = digits(3*a)
        table = build(phases, steps, options)
        rows = [pack_row(table, t) for t in range(3)]
        verify(phases, rows)
        assert max(rank for rank, _ in table.values()) < 11
        masks.extend(hex(row) for row in rows)
    indices = []
    for a in range(729):
        phases = digits(a)
        i = sum((p-phases[0]) % 3 * 3**k for k, p in enumerate(phases)) // 3
        indices.append(str(i))
    path = Path(__file__).with_name('SixTables.lean')
    path.write_text(
        '/-! Generated by pack_six.py. SixCheck verifies these tables against the physical update. -/\n'
        'namespace PhaseFalls.Six\nset_option maxRecDepth 8192\n'
        'def tableIndex : Array Nat := #[\n' + ', '.join(indices) + ']\n'
        'def packedTables : Array Nat := #[\n' + ',\n'.join(masks) + ']\n'
        'end PhaseFalls.Six\n', encoding='ascii', newline='\n')


if __name__ == '__main__':
    main()
