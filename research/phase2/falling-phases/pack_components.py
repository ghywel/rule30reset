"""Build a six-strip certificate that counts recurrent visits and transient steps."""
from itertools import product
from pathlib import Path
import re

import networkx as nx

from pack_six import digits
from probe import transitions


def component_table(phases, steps):
    graph = nx.DiGraph()
    graph.add_nodes_from((t, row) for t in range(3) for row in range(64))
    for t in range(3):
        allowed = sum(1 << j for j, phase in enumerate(phases) if phase == t)
        for row, nxt, falls in steps:
            if not (falls & ~allowed):
                graph.add_edge((t, row), ((t + 1) % 3, nxt))
    dag = nx.condensation(graph)
    visits, levels, heights = {}, {}, {}
    for v in reversed(list(nx.topological_sort(dag))):
        # The phase advances at each update, so singleton SCCs have no loop.
        recurrent = len(dag.nodes[v]["members"]) > 1
        children = list(dag.successors(v))
        visits[v] = int(recurrent) + max((visits[w] for w in children), default=0)
        levels[v] = 2 * visits[v] - int(recurrent)
        heights[v] = 0 if recurrent else 1 + max(
            (heights[w] for w in children if levels[w] == levels[v]), default=0)
        assert 0 <= levels[v] <= 6 and 0 <= heights[v] <= 11
    components = dag.graph["mapping"]
    packed = []
    for t in range(3):
        mask = 0
        for row in range(64):
            v = components[t, row]
            mask |= (16 * levels[v] + heights[v]) << (8 * row)
        packed.append(mask)
    return packed


def verify(phases, masks, tags):
    # Read both packed certificates and compute updates from the literal truth table.
    rule = (0, 1, 1, 1, 1, 0, 0, 0)
    def read(t, row):
        level, height = divmod((masks[t] >> (8 * row)) & 255, 16)
        tag = (tags[t] >> (17 * row)) & 511
        return level, height, tag

    checked = 0
    for t in range(3):
        for row in range(64):
            level, height, tag = read(t, row)
            assert level <= 6
            assert (height == 0 if level % 2 else 1 <= height <= 11)
            for west, east in product(range(2), repeat=2):
                cells = [west, *[(row >> i) & 1 for i in range(6)], east]
                bits = [rule[4*l + 2*c + r] for l,c,r in zip(cells, cells[1:], cells[2:])]
                if any(old and not new and p != t for old, new, p in zip(cells[1:7], bits, phases)):
                    continue
                nxt = sum(bit << j for j, bit in enumerate(bits))
                next_level, next_height, next_tag = read((t + 1) % 3, nxt)
                assert next_level <= level
                if next_level == level:
                    assert (next_tag == tag if level % 2 else next_height < height)
                checked += 1
    return checked


def main():
    directory = Path(__file__).parent
    tags = [int(x, 16) for x in re.findall("0x[0-9a-f]+", (directory / "SixTables.lean").read_text())]
    assert len(tags) == 3 * 243
    steps = list(transitions(6))
    tables = []
    checked = 0
    for a in range(243):
        phases = digits(3 * a)
        masks = component_table(phases, steps)
        checked += verify(phases, masks, tags[3*a:3*a+3])
        tables.extend(hex(m) for m in masks)
    (directory / "SixComponentTables.lean").write_text(
        "/-! Generated by pack_components.py. Each byte stores 16 * level + height. -/\n"
        "namespace PhaseFalls.Six\nset_option maxRecDepth 8192\n"
        "def componentTables : Array Nat := #[\n" + ",\n".join(tables) + "]\n"
        "end PhaseFalls.Six\n", encoding="ascii", newline="\n")
    print(f"Verified {243*3*64} encoded states and {checked} admissible exterior-bit edges.")


if __name__ == "__main__":
    main()
