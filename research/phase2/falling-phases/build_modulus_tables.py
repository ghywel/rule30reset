"""Generate the finite rank certificates for the compressed six-column theorem."""

import argparse
from pathlib import Path

from moduli_probe import functions, make_steps


MODULI = (3, 4, 5, 7, 11, 13, 17)
HERE = Path(__file__).resolve().parent


def candidate_words(m, previous):
    for xs in previous:
        for p in range(m):
            ys = (*xs, p)
            if tuple((q - ys[1]) % m for q in ys[1:]) in previous:
                yield ys


def observations(width, group):
    choices = {}
    for j in range(width - 1):
        by_tick = {}
        for t, s in group:
            bits = (s >> j) & 3
            if by_tick.setdefault(t, bits) != bits:
                break
        else:
            mask = sum(3 << (2*t) for t in by_tick)
            values = sum(bits << (2*t) for t, bits in by_tick.items())
            choices[j] = (mask, values)
    return choices


def join_observations(first, second):
    joined = {}
    for j, (mask, values) in first.items():
        if j in second:
            mask2, values2 = second[j]
            if mask & mask2 & (values ^ values2) == 0:
                joined[j] = (mask | mask2, values | values2)
    return joined


def certify(m, phases, steps):
    size = len(steps)
    width = len(phases)
    edges, _ = functions["graph"](width, m, [{p} for p in phases], steps)
    components, count = functions["components"](m * size, edges)
    groups = [[] for _ in range(count)]
    children = [set() for _ in range(count)]
    for v, component in enumerate(components):
        groups[component].append(divmod(v, size))
        children[component].update(components[target] for target in edges[v]
                                   if components[target] != component)
        assert all(other < component for other in children[component])
    ranks = []
    profiles = []
    for component, group in enumerate(groups):
        choices = observations(width, group)
        if not choices:
            return None
        lower = max((ranks[k] for k in children[component]), default=0)
        for rank in range(lower, len(profiles)):
            merged = join_observations(profiles[rank], choices)
            if merged:
                profiles[rank] = merged
                break
        else:
            rank = len(profiles)
            profiles.append(choices)
        ranks.append(rank)
    predictions = []
    for profile in profiles:
        pair = min(profile)
        predictions.append(pair + (profile[pair][1] << 3))
    assert len(predictions) <= 64
    words = [sum(ranks[components[t*size + s]] << (6*s) for s in range(size)) for t in range(m)]
    return words, predictions


def number_list(values, output=str):
    return "[" + ", ".join(map(output, values)) + "]"


def shape(assignment):
    return number_list(assignment)


def division_line(width, numbers):
    return f"private def rest{width} : List (List Nat) := " + number_list(numbers, shape)


def declaration(name, entries):
    lines = [f"private def {name} : List Certificate := ["]
    for labels, (ranks, reads) in entries:
        lines.append(
            f"  ⟨{shape(labels)}, #{number_list(ranks, hex)}, #{number_list(reads, hex)}⟩,"
        )
    lines.append("]")
    return "\n".join(lines)


def make_module(m):
    source = [
        "import ModulusLayers",
        "",
        "/-! Generated by build_modulus_tables.py. The kernel checks the rank "
        "tables and the coverage of the phase assignments. -/",
        "namespace PhaseFalls.Moduli",
        "set_option maxRecDepth 80000",
        "set_option maxHeartbeats 0",
        "",
    ]
    previous = [(0, p) for p in range(m)]
    for width in range(3, 7):
        steps = make_steps(width)
        rest, entries = [], []
        for labels in candidate_words(m, previous):
            cert = certify(m, labels, steps)
            if cert is None:
                rest.append(labels)
            else:
                entries.append((labels, cert))
        print(f"{m} mod, width {width}: {len(entries)} ruled out, {len(rest)} remaining")
        source.append(division_line(width, rest))
        names = []
        # Check separate blocks to keep the kernel's recursion depth and memory
        # local. Each block translates directly to one closed boolean equality.
        for index in range(0, len(entries), 24):
            name = f"group{width}_{index // 24}"
            names.append(name)
            source.append(declaration(name, entries[index:index+24]))
            source.append(f"private theorem {name}_ok : {name}.all (check {width} {m}) = true := by decide +kernel")
        source.append(f"private def certs{width} := " + (" ++ ".join(names) or "([] : List Certificate)"))
        if len(names) == 1:
            check = "exact " + names[0] + "_ok"
        elif names:
            lemmas = ", ".join(f"{name}_ok" for name in names)
            check = f"simp only [certs{width}, List.all_append, {lemmas}, Bool.and_true]"
        else:
            check = "rfl"
        prev_list = f"pairs {m}" if width == 3 else f"rest{width-1}"
        prev_proof = f"(pairs_classify {m})" if width == 3 else f"class{width-1}"
        source.extend([
            f"private theorem valid{width} : certs{width}.all (check {width} {m}) = true := by {check}",
            f"private theorem cover{width} : ruledOut {m} ({prev_list}) rest{width} = certs{width}.map Certificate.labels := by decide +kernel",
            f"private theorem class{width} : Classifies {width} {m} rest{width} :=",
            f"  classify_step (by decide) (by decide) {prev_proof} valid{width} cover{width}",
            "",
        ])
        previous = rest
    assert not rest
    source.extend([
        f"theorem good{m} {{a : Nat → Nat}} (ha : Valid 6 {m} a) : Good 6 {m} a :=",
        "  of_empty class6 ha",
        "end PhaseFalls.Moduli",
        "",
    ])
    (HERE / f"ModulusData{m}.lean").write_text("\n".join(source), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("modulus", type=int, nargs="*", default=MODULI)
    args = parser.parse_args()
    for modulus in args.modulus:
        if modulus not in MODULI:
            parser.error(f"unsupported modulus {modulus}")
        make_module(modulus)
