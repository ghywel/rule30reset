def alt(t):
    return 1 if t % 2 == 0 else 0


def tick(X, c):
    """One tick of the driven right half: X has bit p - 1 = column p; c is column 0 now."""
    return ((X << 1) | c) ^ (X | (X >> 1))


def row_at(code, T):
    X = code
    for t in range(T):
        X = tick(X, alt(t))
    return X


def dstep(s, x1, x2, W):
    """From an odd tick: the window two ticks later. Column 0 is white, then black."""
    Y = s | (x1 << W) | (x2 << (W + 1))
    Y1 = tick(Y, 0) & ((1 << (W + 1)) - 1)
    return tick(Y1, 1) & ((1 << W) - 1)


def kit_data(d):
    text = open(d + '/Rule30Certificates/GateTrap.lean').read()
    body = re.search(r'def trapCodes : List Nat := \[(.*?)\]', text, re.S).group(1)
    trap = set(int(x) for x in re.findall(r'\d+', body))
    assert len(trap) == 829
    text = open(d + '/Rule30Ether.lean').read()
    body = re.search(r'def etherTable : List \(List Bool\) :=\s*\[(.*?)\]\]', text, re.S).group(1) + ']'
    table = [[x == 'true' for x in re.findall(r'true|false', row)] for row in re.findall(r'\[(.*?)\]', body, re.S)]
    assert len(table) == 7 and all(len(r) == 4 for r in table)
    body = re.search(r'def wallStates : List \(Nat × List Bool\) := \[(.*?)\n\]', text, re.S).group(1)
    walls = [(int(p), [x == 'true' for x in re.findall(r'true|false', cells)])
             for p, cells in re.findall(r'\((\d), \[(.*?)\]\)', body)]
    assert len(walls) == 109 and all(len(c) == 13 for _, c in walls)
    return trap, table, walls


def ether_wall_windows(table, walls, k):
    """The kit's windows 'columns 1..k ether, k + 1..k + 13 a wall state' at the odd ticks, by phase (0 or 2)."""
    out = {0: set(), 2: set()}
    for ph, cells in walls:
        if ph in (0, 2):
            w = 0
            for p in range(1, k + 1):
                w |= int(table[(3 + p) % 7][ph]) << (p - 1)
            for i, b in enumerate(cells):
                w |= int(b) << (k + i)
            out[ph].add(w)
    return out


def closure(start, W):
    seen = set(start); todo = list(start); toggles = True
    while todo:
        s = todo.pop()
        for x1 in (0, 1):
            for x2 in (0, 1):
                n = dstep(s, x1, x2, W)
                toggles &= ((n & 1) != (s & 1))
                if n not in seen:
                    seen.add(n); todo.append(n)
    return seen, toggles


def minimal_closed(S, W):
    """The union of the minimal closed subsets of the closed set S, and how many there are."""
    cl = {s: frozenset(closure([s], W)[0]) for s in S}
    mins = set(c for c in cl.values() if all(cl[v] == c for v in c))
    return set().union(*mins), len(mins)


def gate(code, n):
    X = code; out = []
    for t in range(2 * n):
        X = tick(X, alt(t))
        if t % 2 == 0:
            out.append(X & 1)
    return out                                       # out[q] = column 1 at tick 2q + 1


def fate(code, trap, ew, T=8000):
    """('trap', tick) | ('ether', tick, k) | ('none', T, gate period guess)."""
    X = code; g = []
    for t in range(T):
        X = tick(X, alt(t))
        if t % 2 == 0:                               # X is now the row at the odd tick t + 1
            if X & 0xFFFF in trap:
                return ('trap', t + 1)
            for k, sets in ew:
                if X & ((1 << (k + 13)) - 1) in sets[(t + 1 + 3) % 4]:
                    return ('ether', t + 1, k)
            g.append(X & 1)
    tail = g[-600:]
    per = next((p for p in range(1, 200) if all(tail[i] == tail[i + p] for i in range(len(tail) - p))), None)
    return ('none', T, per)


def main():
    t00 = time.time()
    trap, table, walls = kit_data(sys.argv[1])
    W = 19; M = (1 << W) - 1

    print('A. Controls.')
    X = 0; first = None
    for t in range(400):
        X = tick(X, alt(t))
        if t % 2 == 0 and X & 0xFFFF in trap:
            first = t + 1; break
    print('   the empty right half first enters the trap at tick %s (kit: 293)' % first)
    for code in (31, 495):
        g = gate(code, 3000)
        print('   %d: gate = parity of the step for q < 3000: %s' % (code, all(g[q] == q % 2 for q in range(3000))))
    g = gate(175, 3000)
    print('   175: gate toggles from step 4 for q < 3000: %s; window at tick 9 = %d (66c410: 106656)'
          % (all(g[q + 1] != g[q] for q in range(4, 2999)), row_at(175, 9) & M))
    t28998 = next(t for t in range(1, 60, 2) if row_at(28998, t) & 0xFFFF in trap)
    g = gate(1891, 400)
    print('   28998 is in the trap from tick %d (kit: lock5 entered at 15); 1891 reads from tick 27: %s (kit: 0101000)'
          % (t28998, ''.join(map(str, g[13:27]))))

    if len(sys.argv) > 2 and sys.argv[2] == 'control':
        return
    print('B. The lock at 19 columns.')
    ew19 = ether_wall_windows(table, walls, 6)
    K19 = ew19[0] | ew19[2]
    print('   the kit\'s ether-and-wall windows at the odd phases: %d (phase 0: %d, phase 2: %d)'
          % (len(K19), len(ew19[0]), len(ew19[2])))
    Kc, Ktog = closure(K19, W)
    print('   that set is closed under the double step: %s; the gate toggles on every edge: %s' % (Kc == K19, Ktog))
    Kmin, nmin = minimal_closed(K19, W)
    print('   its minimal closed subsets: %d, with %d windows in all' % (nmin, len(Kmin)))
    ent = {31: row_at(31, 9) & M, 495: row_at(495, 5) & M, 175: row_at(175, 9) & M}
    gen = {}
    for code, w in ent.items():
        S, tog = closure([w], W)
        core, n = minimal_closed(S, W)
        gen[code] = S
        print('   %d: entry window %d; generated closed set %d windows, inside the kit\'s set: %s; gate toggles: %s; '
              'minimal closed part %d windows (%d set), equal to the kit set\'s: %s'
              % (code, w, len(S), S <= K19, tog, len(core), n, core == Kmin))
    H3 = set(H3_CODES)
    Hc, Htog = closure(H3, W)
    print('   h3artfield\'s 53 codes: closed: %s; inside the kit\'s set: %s; contain the minimal part: %s; '
          'extra windows beyond it: %s' % (Hc == H3, H3 <= K19, Kmin <= H3, sorted(H3 - Kmin)))
    print('   kit set minus the minimal part: %d windows; kit set minus h3artfield\'s: %d'
          % (len(K19 - Kmin), len(K19 - H3)))

    print('C. The window graph at 19 columns, outer cells free.')
    s = np.arange(1 << W, dtype=np.uint32)
    succ = []
    for x1 in (0, 1):
        for x2 in (0, 1):
            Y = s | np.uint32(x1 << W) | np.uint32(x2 << (W + 1))
            Y1 = ((Y << np.uint32(1)) ^ (Y | (Y >> np.uint32(1)))) & np.uint32((1 << (W + 1)) - 1)
            Y2 = (((Y1 << np.uint32(1)) | np.uint32(1)) ^ (Y1 | (Y1 >> np.uint32(1)))) & np.uint32(M)
            succ.append(Y2)
    for w in random.Random(1).sample(range(1 << W), 2000):          # the table against the scalar double step
        assert [int(succ[2 * x1 + x2][w]) for x1 in (0, 1) for x2 in (0, 1)] == [dstep(w, x1, x2, W) for x1 in (0, 1) for x2 in (0, 1)]

    def attractor(target):
        A = target.copy(); n = 0
        while True:
            B = A | (A[succ[0]] & A[succ[1]] & A[succ[2]] & A[succ[3]])
            n += 1
            if (B == A).all():
                return A, n
            A = B
    inK = np.zeros(1 << W, dtype=bool); inK[list(K19)] = True
    inT = np.zeros(1 << 16, dtype=bool); inT[list(trap)] = True
    inT = inT[s & np.uint32(0xFFFF)]
    AE, nE = attractor(inK); AT, nT = attractor(inT)
    print('   forced into the lock: %d windows (%d rounds); forced into the trap: %d (%d rounds); neither: %d'
          % (AE.sum(), nE, AT.sum(), nT, (1 << W) - AE.sum() - AT.sum()))
    assert not (AE & AT).any()

    print('D. Prefixes of L <= 20 cells.')
    X = np.arange(1 << 20, dtype=np.uint32)
    w1 = (((X << np.uint32(1)) | np.uint32(1)) ^ (X | (X >> np.uint32(1)))) & np.uint32(M)     # the window at tick 1
    for x in random.Random(2).sample(range(1 << 20), 2000):
        assert int(w1[x]) == row_at(x, 1) & M
    fE = AE[w1]; fT = AT[w1]
    print('   of the 2^20 prefixes of 20 cells: forced into the lock %d (%.4f%%), into the trap %d (%.4f%%), '
          'neither %d (%.4f%%)' % (fE.sum(), 100 * fE.mean(), fT.sum(), 100 * fT.mean(),
                                   (~fE & ~fT).sum(), 100 * (~fE & ~fT).mean()))
    forcedE = {}; forcedT = {}
    for L in range(0, 21):
        forcedE[L] = fE.reshape(1 << (20 - L), 1 << L).all(axis=0)
        forcedT[L] = fT.reshape(1 << (20 - L), 1 << L).all(axis=0)
    for name, forced in (('lock', forcedE), ('trap', forcedT)):
        counts = []; shortest = None
        for L in range(1, 21):
            f = forced[L]; parent = forced[L - 1][np.arange(1 << L) & ((1 << (L - 1)) - 1)]
            mins = np.nonzero(f & ~parent)[0]
            counts.append(len(mins))
            if len(mins) and shortest is None:
                shortest = (L, [int(v) for v in mins[:12]], len(mins))
        print('   minimal prefixes forcing the %s, by length 1..20: %s' % (name, counts))
        if shortest:
            L, vs, n = shortest
            print('   the shortest force the %s with %d cells: %d of them, e.g. %s (cells 1..%d, cell 1 first)'
                  % (name, L, n, ', '.join(format(v, '0%db' % L)[::-1] for v in vs), L))
        meas = sum(c / 2.0 ** (i + 1) for i, c in enumerate(counts))
        print('   their measure: %.6f%%' % (100 * meas))

    print('E. The three seeds, padded with white.')
    rnd = random.Random(20261122)
    ew = [(k, ether_wall_windows(table, walls, k)) for k in (6, 13, 20, 27, 34)]
    for code, n in ((31, 5), (495, 9), (175, 8)):
        res = {}
        for L in range(n, 33):
            if L <= 20:
                ok = bool(forcedE[L][code])
            else:
                ok = any(AE[row_at(code, t) & M] for t in range(1, L - 19 + 1, 2))
            res[L] = ok
        least = min((L for L in res if res[L]), default=None)
        print('   %d: forced for every tail from L = %s cells (8d7751 and 66c410 state %d)'
              % (code, least, {31: 28, 495: 24, 175: 28}[code]))
        for L in range(n, (least or 33)):
            wit = None
            tails = [1, 3, (1 << 64) - 1] + [rnd.getrandbits(64) for _ in range(4000)]
            for tl in tails:
                c2 = code | (tl << L)
                f = fate(c2, trap, ew, T=4000)
                if f[0] == 'trap':
                    wit = (tl, f[1]); break
            print('     L = %2d not forced: %s' % (L, 'the tail %d (cells from %d on) enters the trap at tick %d'
                                                   % (wit[0], L + 1, wit[1]) if wit else 'NO TRAP TAIL FOUND: open'))

    print('F. Every right half below 2^16, white tail.')
    kinds = {}; least = {}; slow = (0, 0); small = []
    for code in range(1 << 16):
        f = fate(code, trap, ew)
        key = f[0] if f[0] != 'ether' else 'ether k=%d' % f[2]
        if f[0] == 'none':
            key = 'neither by tick 8000, gate period %s' % f[2]
        kinds[key] = kinds.get(key, 0) + 1
        least.setdefault(key, code)
        if f[0] != 'none' and f[1] > slow[0]:
            slow = (f[1], code)
        if f[0] != 'trap' and code < 512:
            small.append((code, key))
    for key in sorted(kinds):
        print('   %-44s %6d   least code %d' % (key, kinds[key], least[key]))
    print('   the slowest certificate: tick %d (code %d)' % slow)
    print('   below 512, not into the trap: %s' % '; '.join('%d (%s)' % x for x in small))
    print('time %.0f s' % (time.time() - t00))


if __name__ == '__main__':
    main()
