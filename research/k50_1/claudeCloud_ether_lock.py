#!/usr/bin/env python3
"""claudeCloud_ether_lock.py: pull K50.1 (ledger K66) and KIT-REPAIR step 6.

Our portal entry R30-20261024-8d7751 puts two families of right halves into the kit's ether-and-wall trap beside the
alternating column, so that their gate alternates: every right half agreeing with the seed 31 on cells 1..28, or with
495 on cells 1..24. h3artfield's R30-20261122-66c410 does the same for the seed 175 on cells 1..28, with a list of 53
windows. This probe asks what that lock is, who enters it, and how short a prefix forces it.

Conventions (the kit's). Column 0 is the alternating column, black at the even ticks. Columns p >= 1 evolve by
    new(p) = old(p - 1) xor (old(p) or old(p + 1)).
A right half is a number: bit j is cell j + 1 at tick 0. A window is the columns 1..W at an odd tick: bit i is
column i + 1. The gate is u(q) = column 1 at tick 2q + 1. From an odd tick, the window two ticks later is a function
of the window and of x1, x2, the cells of columns W + 1 and W + 2 at the odd tick (the kit's `dstep`).

The kit's sets, read from its Lean files as data:
  trap   the 829 windows of 16 columns of Rule30GateTrap (closed; inside it the gate's black cells are 3 or 5 apart);
  ether  Rule30Ether's 7 x 4 table, and its 109 wall states (phase, 13 cells). With the alternating column as ether
         column B4, the kit's trap invariant keeps "columns 1..k ether, columns k + 1..k + 13 a wall state" for ever
         when k = 6, 13, 20, ...; at an odd tick t the phase is (t + 3) mod 4.

Parts
  A  Controls with known answers: the empty right half first enters the trap at tick 293 (kit); the gates of 31 and
     495 are the parity of the step from the start (8d7751); 175 toggles from step 4 and its window at tick 9 is
     106656 (66c410); 28998 is in the trap by tick 15 and 1891 reads 0101000 from tick 27 (Rule30SidewaysLocks).
  B  The lock at 19 columns: the set closed under the double step, with all four (x1, x2), generated by each entry
     window (31 at tick 9, 495 at tick 5, 175 at tick 9); whether the gate toggles on every edge; their minimal
     closed subsets; the kit's ether-and-wall windows at the odd phases; h3artfield's 53 codes.
  C  The window graph at 19 columns with free outer cells: which windows are forced into the lock (every path
     reaches it), which into the trap. This is sound for forcing, not complete: real outer cells are not free.
  D  Prefixes: for every prefix of L <= 20 cells, is every right half with that prefix forced into the lock (by C)?
     The minimal forcing prefixes by length, the shortest ones, and their total measure.
  E  The three seeds, padded with white: the least number of cells L for which every right half agreeing on cells
     1..L is forced; for each shorter L, a tail that enters the trap instead, found by search (the trap is closed,
     so such a right half never has an alternating gate).
  F  Every right half below 2^16 (white tail), followed exactly: into the trap, into the ether and a wall (k = 6,
     13, 20, 27, 34), or neither by tick 8000; the least code of each kind.

    python3 claudeCloud_ether_lock.py KIT_LEAN_DIR            (KIT_LEAN_DIR = .../lean/Ruliology/CellularAutomata)
    python3 claudeCloud_ether_lock.py KIT_LEAN_DIR control    (part A only)
"""
