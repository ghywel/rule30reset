"""Produce the 40-sample backward certificate for the kit's independent exterior inputs."""

import argparse
from pathlib import Path

import numpy as np

from wheel_bridge import U, graph, tick


def pack_fields(values, bits):
    return sum(int(v) << (bits*i) for i, v in enumerate(values))


def bank_lookup(values, first=0, indent="  "):
    """A balanced lookup lets the Lean kernel reduce just the chosen numeral."""
    if len(values) == 1:
        return hex(values[0])
    middle = len(values)//2
    left = bank_lookup(values[:middle], first, indent+"  ")
    right = bank_lookup(values[middle:], first+middle, indent+"  ")
    return f"if k < {first+middle} then\n{indent}  {left}\n{indent}else\n{indent}  {right}"


def certificate(kit):
    words, _, trap = graph(kit, 16)
    gate = [int(U[2*((15+i) % 28)]) for i in range(40)]
    mask = 65535
    edges = np.stack([tick((tick(words + ((e % 2) << 16), 0) & mask) + ((e // 2) << 16), 1)
                      & mask for e in range(4)], axis=1)
    labels = np.zeros(len(words), dtype=np.int64)
    bad = ~trap
    for i in reversed(range(40)):
        bad &= (words & 1) == gate[i]
        labels[bad] |= 1 << i
        bad = np.any(bad[edges], axis=1)
    assert not np.any(labels & 1)
    palette, inverse = np.unique(labels, return_inverse=True)
    assert len(palette) <= 64
    banks = [pack_fields(inverse[lo::256], 6) for lo in range(256)]
    unique = sorted(set(banks))
    assert len(unique) <= 256 and all(0 <= label < 2**40 for label in palette)
    indices = [unique.index(k) for k in banks]
    return "\n".join([
        "module\n\n/-! Generated by make_marker.py. Bit j marks a possible exterior-ending suffix. -/",
        "@[expose] public section\nnamespace Ruliology.CellularAutomata.WheelMarker.Data",
        f"def labels : Nat := {hex(pack_fields(palette, 40))}\n",
        f"def bankIndex : Nat := {hex(pack_fields(indices, 8))}\n",
        "def bank (k : Nat) : Nat :=\n  " + bank_lookup(unique) + "\n",
        "end Ruliology.CellularAutomata.WheelMarker.Data\n",
    ])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("kit", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_bytes(certificate(args.kit).encode())
