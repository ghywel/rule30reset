"""Generate KIT-INDEX.md from kit/index.jsonl; with --restamp REV, first record REV as the synced kit commit.

  python3 kit/build.py                 # regenerate KIT-INDEX.md from the index and the current stamp
  python3 kit/build.py --restamp REV   # only when kit/check.py --rev REV reports no row to digest

Restamping writes kit/stamp.json (commit, date, hashes of the watched prose blocks) and rewrites the stamp line at
the top of KIT.md and the commit named in its first paragraph. It refuses while any row at REV is new, changed or
missing from the index: that is the lockstep rule. Review KIT.md before restamping; the stamp says you did.
"""
import argparse, json, re, sys
from collections import Counter
import kitlib as K

ap = argparse.ArgumentParser()
ap.add_argument('--restamp')
a = ap.parse_args()
idx = K.load_index()
if a.restamp:
    live = {r['key']: r for s in ('lean', 'equivalents') for r in K.rows(a.restamp, s)}
    stale = [k for k, r in live.items() if k not in idx or idx[k]['sha'] != r['sha']] + [k for k in idx if k not in live]
    if stale:
        print('refusing to restamp: %d row(s) not in step with %s; run kit/check.py --rev %s' % (len(stale), a.restamp, a.restamp))
        sys.exit(1)
    for k, r in live.items():
        idx[k]['line'] = r['line']
    K.save_index(idx)
    full = K.resolve(a.restamp)
    stamp = {'commit': full, 'date': K.commit_date(a.restamp), 'watched': K.watched(a.restamp)}
    json.dump(stamp, open(K.STAMP, 'w'), indent=1, sort_keys=True)
    s = open(K.KIT_MD).read()
    line = '<!-- kit-commit: %s %s -->' % (full[:7], stamp['date'])
    s = K.STAMP_RE.sub(line, s, count=1) if K.STAMP_RE.search(s) else line + '\n' + s
    s = K.PROSE_RE.sub('at commit `%s` (main, %s)' % (full[:7], stamp['date']), s, count=1)
    open(K.KIT_MD, 'w').write(s)
    print('restamped to', full[:7], stamp['date'])
stamp = K.load_stamp()
if not stamp:
    sys.exit('no kit/stamp.json yet: run with --restamp REV first')

def who(w):
    w = re.sub(r'\s*\+ext:\s*Quint(?: \(Gemini\))?', '', w)
    w = re.sub(r';?\s*\+G\.P\.J\.W\. Quint & Gemini', '', w)
    w = re.sub(r',\s*Quint \(Gemini\)$', '', w)
    return w.replace('+ext:', 'ext:').strip(' ;,') or 'kit'

lean = [r for r in idx.values() if r['src'] == 'lean']
eq = [r for r in idx.values() if r['src'] == 'equivalents']
twice = Counter(r['cell'] for r in lean)
L = ['<!-- kit-commit: %s %s -->' % (stamp['commit'][:7], stamp['date']), '# Kit index: one line per catalogue row', '',
     '*Generated by `kit/build.py` from `kit/index.jsonl`; do not edit by hand. The Rule 30 Prize kit at commit `%s`'
     % stamp['commit'][:7], '(main, %s): every table row of `lean/README.md` (%d) and `equivalents/README.md` (%d), condensed. Each line:'
     % (stamp['date'], len(lean), len(eq)),
     'module, date added, contributors, weight, what is proved, and the open statements it defines or uses with the',
     'implications it proves. Weight 3 = a reduction between open statements, a new open statement, a barrier, or an',
     'exclusion of an infinite family; 2 = a substantial theorem; 1 = corollaries, extensions, tooling and certificate',
     'data. Almost every row added after 20 October also carries extensions by G.P.J.W. Quint with Gemini; that credit',
     'is omitted. A module listed in two catalogue tables has two lines, tagged with the table. The concise map is',
     '[KIT.md](KIT.md); [KIT-UPDATE.md](KIT-UPDATE.md) keeps both in step with the kit. Verify against the kit before citing.*', '']
for th, title in K.THEMES:
    rs = sorted([r for r in lean if r['theme'] == th], key=lambda r: (-r['W'], r['date'], r['line']))
    if not rs:
        continue
    L.append('## %s (%d)\n' % (title, len(rs)))
    for r in rs:
        tag = ' [%s]' % ('added' if r['section'] == 'Added in the kit' else 'catalogue: ' + r['section']) if twice[r['cell']] > 1 else ''
        s = '- **%s**%s · %s · %s · W%d. %s' % (r['name'], tag, r['date'], who(r['who']), r['W'], r['proved'])
        if r['open'] not in ('-', ''):
            s += ' *Open/implications:* ' + r['open']
        L.append(s)
    L.append('')
L.append('## Equivalent forms and sufficient conditions (`equivalents/`, %d modules)\n' % len(eq))
for k, t in K.KINDS:
    es = sorted([e for e in eq if e['kind'] == k], key=lambda e: e['line'])
    if es:
        L.append('### %s (%d)\n' % (t, len(es)))
        L += ['- **%s** (%s). %s' % (e['name'], e['field'], e['form']) for e in es]
        L.append('')
open(K.KIT_INDEX_MD, 'w').write('\n'.join(L))
print('KIT-INDEX.md: %d lean rows, %d equivalents, stamp %s' % (len(lean), len(eq), stamp['commit'][:7]))
